{- | A program the codec can take a round trip on: well-scoped, at version
1.0.0 or 1.1.0. Below 1.1.0 the term has no @constr@ or @case@, since the
decoder refuses them there.
-}
newtype Encodable = Encodable (Program DeBruijn ())
  deriving stock (Eq, Show)

instance Arbitrary Encodable where
  arbitrary = do
    version <- elements [Version 1 0 0, Version 1 1 0]
    Encodable . Program () version <$> genTerm (version >= Version 1 1 0) 0
  shrink (Encodable (Program () v t)) = Encodable . Program () v <$> shrinkTerm 0 t

{- | A constant whose type is nested up to four levels deep, each depth
equally likely. The usual size-based generator hardly ever produces deep
types like a pair of lists of pairs, and those are what test the type
tags.
-}
newtype Nested = Nested Constant
  deriving stock (Eq, Show)

instance Arbitrary Nested where
  arbitrary = do
    depth <- choose (0 :: Int, 4)
    Nested <$> genConstant depth
  shrink (Nested c) = Nested <$> shrinkConstant c

-- A term with the given number of binders in scope. Var only appears where
-- the depth allows it, and the depth rises by one under every LamAbs.
genTerm :: Bool -> Word64 -> Gen (Term DeBruijn ())
genTerm constrCase depth = sized (go depth)
  where
    go :: Word64 -> Int -> Gen (Term DeBruijn ())
    go d size
      | size <= 0 = oneof (leaves d)
      | otherwise = oneof (leaves d <> branches d)

    leaves :: Word64 -> [Gen (Term DeBruijn ())]
    leaves d =
      [ pure (Error ())
      , Constant () <$> (genConstant =<< choose (0, 2))
      , Builtin () <$> arbitraryBoundedEnum
      ]
        <> [Var () . DeBruijn <$> choose (1, d) | d > 0]

    -- DeBruijn 0 in a binder position is a placeholder: the wire carries
    -- nothing there, and no Var refers to it.
    branches :: Word64 -> [Gen (Term DeBruijn ())]
    branches d =
      [ LamAbs () (DeBruijn 0) <$> half (d + 1)
      , Apply () <$> half d <*> half d
      , Delay () <$> half d
      , Force () <$> half d
      ]
        <> [ Constr () <$> arbitrary <*> scaleDown (listOf (half d)) | constrCase ]
        <> [ Case () <$> half d <*> (Vector.fromList <$> scaleDown (listOf (half d))) | constrCase ]

    half :: Word64 -> Gen (Term DeBruijn ())
    half d = scale (`quot` 2) (genTerm constrCase d)

-- A lambda's body is only shrunk in place, one deeper, so no variable is
-- left pointing past the binder it referred to.
shrinkTerm :: Word64 -> Term DeBruijn () -> [Term DeBruijn ()]
shrinkTerm d = \case
  Var () (DeBruijn i) -> [Var () (DeBruijn j) | j <- shrink i, j >= 1]
  Constant () c -> Constant () <$> shrinkConstant c
  Builtin () f -> Builtin () <$> takeWhile (< f) [minBound ..]
  Error () -> []
  Delay () t -> t : (Delay () <$> shrinkTerm d t)
  Force () t -> t : (Force () <$> shrinkTerm d t)
  LamAbs () n t -> LamAbs () n <$> shrinkTerm (d + 1) t
  Apply () f x ->
    [f, x]
      <> [Apply () f' x | f' <- shrinkTerm d f]
      <> [Apply () f x' | x' <- shrinkTerm d x]
  Constr () t xs -> xs <> (Constr () t <$> shrinkList (shrinkTerm d) xs)
  Case () s xs ->
    (s : Vector.toList xs)
      <> [Case () s' xs | s' <- shrinkTerm d s]
      <> (Case () s . Vector.fromList <$> shrinkList (shrinkTerm d) (Vector.toList xs))

-- A type exactly this deep, together with a generator for its values, so
-- the two always match. No BLS types, whose values flat never carries.
genWire :: Int -> Gen (Ty, Gen Constant)
genWire depth
  | depth <= 0 =
      elements
        [ (TyInteger, CInteger <$> arbitrary)
        , (TyByteString, CByteString . BS.pack <$> listOf arbitrary)
        , (TyString, CString . T.pack <$> listOf genChar)
        , (TyUnit, pure CUnit)
        , (TyBool, CBool <$> arbitrary)
        , (TyData, CData <$> scaleDown genData)
        , (TyValue, CValue <$> scaleDown genValue)
        ]
  | otherwise =
      oneof
        [ do
            (t, g) <- sub
            pure (TyList t, CList t <$> scaleDown (listOf g))
        , do
            (t, g) <- sub
            pure (TyArray t, CArray t . Strict.fromList <$> scaleDown (listOf g))
        , do
            (a, ga) <- sub
            (b, gb) <- sub
            pure (TyPair a b, CPair a b <$> ga <*> gb)
        ]
  where
    sub :: Gen (Ty, Gen Constant)
    sub = genWire (depth - 1)

genConstant :: Int -> Gen Constant
genConstant depth = snd =<< genWire depth

-- Only the contents shrink. Shrinking a type would leave a constant whose
-- tags no longer match its value.
shrinkConstant :: Constant -> [Constant]
shrinkConstant = \case
  CInteger i -> CInteger <$> shrink i
  CByteString bs -> CByteString . BS.pack <$> shrink (BS.unpack bs)
  CString t -> CString . T.pack <$> shrink (T.unpack t)
  CUnit -> []
  CBool b -> CBool <$> shrink b
  CList t xs -> CList t <$> shrinkList shrinkConstant xs
  CArray t xs -> CArray t . Strict.fromList <$> shrinkList shrinkConstant (Strict.toList xs)
  CPair a b x y ->
    [CPair a b x' y | x' <- shrinkConstant x]
      <> [CPair a b x y' | y' <- shrinkConstant y]
  CData _ -> []
  CValue v ->
    [ CValue (pack (Map.fromList (map (fmap Map.fromList) smaller)))
    | let outer = [(c, Map.toList ts) | (c, ts) <- Map.toList (unpack v)]
    , smaller <- shrinkList (const []) outer
    ]

-- Characters of several UTF-8 lengths, since strings are encoded as UTF-8.
genChar :: Gen Char
genChar = elements $ ['a' .. 'z'] <> "\xe9\x3bb\x20ac\x65e5\x10348"

scaleDown :: Gen a -> Gen a
scaleDown = scale (`quot` 4)

{- | A 'Data.Data' value. The CBOR encoding changes form at several boundaries:
which tag a constructor index gets, where an integer stops fitting 64 bits,
where a byte string or a big integer's bytes pass 64 and get chunked. Each
draw picks a range on either side of one of those, rather than leaving them
to chance. Indices stay within 0 to 2^64 - 1, which is what plutus-core can
read back.
-}
genData :: Gen Data.Data
genData = sized go
  where
    go :: Int -> Gen Data.Data
    go size
      | size <= 0 = oneof leaves
      | otherwise = oneof (leaves <> branches)

    leaves :: [Gen Data.Data]
    leaves = [Data.I <$> genInteger, Data.B <$> genBytes]

    branches :: [Gen Data.Data]
    branches =
      [ Data.Constr <$> genIndex <*> scaleDown (listOf smaller)
      , Data.Map <$> scaleDown (listOf ((,) <$> smaller <*> smaller))
      , Data.List <$> scaleDown (listOf smaller)
      ]

    smaller :: Gen Data.Data
    smaller = scale (`quot` 2) genData

    genIndex :: Gen Integer
    genIndex = oneof [choose (0, 6), choose (7, 127), choose (128, 2 ^ (64 :: Int) - 1)]

    genInteger :: Gen Integer
    genInteger =
      oneof
        [ arbitrary
        , choose (2 ^ (64 :: Int) - 2, 2 ^ (64 :: Int) + 2)
        , choose (-(2 ^ (64 :: Int)) - 2, -(2 ^ (64 :: Int)) + 2)
        , choose (2 ^ (512 :: Int) - 2, 2 ^ (512 :: Int) + 2)
        , choose (-(2 ^ (520 :: Int)), 2 ^ (520 :: Int))
        ]

    genBytes =
      fmap BS.pack . flip vectorOf arbitrary
        =<< oneof [choose (0, 3), choose (62, 67), choose (126, 130)]

{- | A 'Value' built to meet the codec's edges: keys of length 0, 1, 31 and 32
over a two-letter alphabet, so one key is often a prefix of another and the
order check has something to do, and quantities at the ends of the 128-bit
range and either side of 2^63 and 2^64. Zero quantities and empty token
lists are drawn too, for 'pack' to remove.
-}
genValue :: Gen Value
genValue = do
  currencies <- choose (0, 4)
  entries <- vectorOf currencies ((,) <$> genKey <*> (choose (0, 4) >>= flip vectorOf ((,) <$> genKey <*> genQuantity)))
  pure (pack (Map.fromList [(c, Map.fromList ts) | (c, ts) <- entries]))
  where
    genKey = do
      len <- elements [0, 1, 1, 2, 31, 32]
      bytes <- BS.pack <$> vectorOf len (elements [0x00, 0x01])
      maybe (error "genValue: key too long") pure (k bytes)

    genQuantity = do
      n <-
        oneof
          [ choose (-3, 3)
          , choose (2 ^ (63 :: Int) - 2, 2 ^ (63 :: Int) + 2)
          , choose (-(2 ^ (64 :: Int)) - 2, -(2 ^ (64 :: Int)) + 2)
          , choose (2 ^ (127 :: Int) - 3, 2 ^ (127 :: Int) - 1)
          , choose (-(2 ^ (127 :: Int)), -(2 ^ (127 :: Int)) + 2)
          , choose (-(2 ^ (127 :: Int)), 2 ^ (127 :: Int) - 1)
          ]
      maybe (error "genValue: quantity out of range") pure (quantity n)

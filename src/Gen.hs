{- | Generators for the codec's round trips, copied from cardano-uplc's test
suite so the programs here are drawn the way its own tests draw them. Keep the
two in step.

A constant is generated by picking its type first and then a value of that
type, so its type tags always match what is inside. Terms are generated
knowing how many lambdas enclose them, so every variable refers to one of
them. Shrinking keeps both of these true. 'Data.Data' values are drawn to reach
the edges of their CBOR encoding.
-}
module Gen (
  Encodable (Encodable),
  Nested (Nested),
  genData,
  genValue,
) where

import Data.ByteString qualified as BS
import Data.Map.Strict qualified as Map
import Data.Text qualified as T
import Data.Vector qualified as Vector
import Data.Vector.Strict qualified as Strict
import Data.Word (Word64)
import Test.QuickCheck (
  Arbitrary (arbitrary, shrink),
  Gen,
  arbitraryBoundedEnum,
  choose,
  elements,
  listOf,
  oneof,
  scale,
  shrinkList,
  sized,
  vectorOf,
 )
import Cardano.UPLC.Constant (Constant (..))
import Cardano.UPLC.Data qualified as Data
import Cardano.UPLC.Name (DeBruijn (DeBruijn))
import Cardano.UPLC.Term (Program (Program), Term (..), Version (Version))
import Cardano.UPLC.Ty (Ty (..))
